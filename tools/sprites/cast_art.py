"""Pixel data for the Dernier cast (16x16 frames, GB Studio classic order).

Glyphs: '.' transparent, 'o' light (skin / highlight), '+' middle (clothes),
'#' dark (hair / outline). On GBC each character gets its own sprite palette,
so the same three shades read as different skin, clothes and hair colours.

Characters are assembled from parts so they stay consistent:
  head (8 rows, per direction) + body (7 rows, per direction & build)
Walk frames move the legs and swing the arms. Everything here is a visual
interpretation for draft 1. The owner draws the final art: once an exported
.png is hand-edited, stop regenerating it (see CLAUDE.md).

Frame order per walking strip (96x16): down A, down B, up A, up B, right A,
right B. GB Studio flips "right" for "left".
"""

BLANK = "." * 16


def _pad(rows, n):
    return rows + [BLANK] * (n - len(rows))



def _compose(name, direction, stride):
    h = HEADS[name][direction]
    build = BUILD.get(name, "slim")
    key = direction + ("_b" if stride else "")
    body = BODIES[build][key]
    rows = list(h[:9]) + list(body)
    if build == "child":
        # children stand lower: drop the whole figure by 2 rows
        rows = [BLANK, BLANK] + rows[:14]
    for i, r in BODY_TOUCH.get(name, {}).get(direction, {}).items():
        rows[i if build != "child" else i + 2] = r
    rows = _pad(rows[:16], 16)
    if stride and direction != "right":
        # mid-stride bob: lift the head one pixel
        rows = rows[1:9] + [rows[8]] + rows[9:]
        rows = rows[:16]
    return rows


def walk_frames(name):
    return {
        "down_a": _compose(name, "down", False),
        "down_b": _compose(name, "down", True),
        "up_a": _compose(name, "up", False),
        "up_b": _compose(name, "up", True),
        "right_a": _compose(name, "right", False),
        "right_b": _compose(name, "right", True),
    }


